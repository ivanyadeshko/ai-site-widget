/**
 * Идемпотентный засев: домашняя страница пересоздаётся, globals
 * перезаписываются. Деструктивен — вызывается только через гард
 * ENABLE_SEED_ROUTES (см. src/app/api/seed/route.ts).
 */
export async function seedLanding(payload: Payload): Promise<{ pageId: string | number }> {
  const existing = await payload.find({
    collection: 'pages',
    where: { slug: { equals: 'home' } },
    limit: 1,
  })
  for (const doc of existing.docs) {
    await payload.delete({ collection: 'pages', id: doc.id, overrideAccess: true })
  }

  const page = await payload.create({
    collection: 'pages',
    overrideAccess: true,
    data: {
      title: 'Vell — голосовой AI-агент для сайта',
      slug: 'home',
      layout,
      seo: {
        title: 'Vell — голосовой AI-агент для вашего сайта',
        description:
          'Виджет, который разговаривает с посетителями голосом и в чате, отвечает на вопросы и оставляет вам контакт заинтересованного клиента.',
      },
    },
  })

  await payload.updateGlobal({
    slug: 'header',
    overrideAccess: true,
    data: {
      brand: 'Vell',
      navItems: [
        { label: 'Возможности', href: '#features' },
        { label: 'Как это работает', href: '#how' },
        { label: 'Тарифы', href: '#pricing' },
        { label: 'Вопросы', href: '#faq' },
      ],
      loginLabel: 'Войти',
      registerLabel: 'Начать бесплатно',
    },
  })

  await payload.updateGlobal({
    slug: 'pricing',
    overrideAccess: true,
    data: {
      title: 'Тарифы',
      subtitle: 'Идёт открытая бета: доступ бесплатный, платных списаний нет.',
      plans: [
        {
          name: 'Старт',
          description: 'Чтобы поставить агента на сайт и посмотреть, о чём спрашивают посетители.',
          priceNote: 'бесплатно на бете',
          isHighlighted: false,
          features: [
            { text: 'Один виджет' },
            { text: 'Голос и чат' },
            { text: 'Лиды и расшифровки в кабинете' },
          ],
          ctaLabel: 'Начать бесплатно',
        },
        {
          name: 'Бизнес',
          description: 'Для нескольких сайтов и больших объёмов разговоров.',
          priceNote: 'по запросу',
          isHighlighted: true,
          features: [
            { text: 'Несколько виджетов' },
            { text: 'Увеличенные лимиты' },
            { text: 'Помощь с настройкой' },
          ],
          ctaLabel: 'Обсудить',
        },
      ],
      note: 'Тарифы объявим до конца беты. Аккаунты и данные бета-периода сохранятся.',
    },
  })

  await payload.updateGlobal({
    slug: 'footer',
    overrideAccess: true,
    data: {
      tagline: 'Vell — голосовой AI-агент для вашего сайта.',
      columns: [
        {
          title: 'Продукт',
          links: [
            { label: 'Возможности', href: '#features' },
            { label: 'Как это работает', href: '#how' },
            { label: 'Тарифы', href: '#pricing' },
          ],
        },
        {
          title: 'Поддержка',
          links: [{ label: 'Вопросы и ответы', href: '#faq' }],
        },
      ],
      copyright: '© Vell',
    },
  })

  return { pageId: page.id }
}
