import { describe, expect, it } from 'vitest';
import { CSV_BOM, csvCell, csvLine } from '../src/panel/csv.ts';

describe('CSV лидов', () => {
  it('разделители, кавычки и переводы строк не рвут файл', () => {
    // Excel в русской локали читает `;` как разделитель, а RFC 4180 — `,`.
    // Экранируем ОБА: файл открывают и тем, и другим.
    expect(csvCell('Иванов, Иван')).toBe('"Иванов, Иван"');
    expect(csvCell('скидка; сегодня')).toBe('"скидка; сегодня"');
    expect(csvCell('он сказал "да"')).toBe('"он сказал ""да"""');
    expect(csvCell('первая\nвторая')).toBe('"первая\nвторая"');
    expect(csvCell('обычный текст')).toBe('обычный текст');
  });

  it('формула из лида не исполняется в Excel: ведущий апостроф', () => {
    // Лид приходит из формы на ЧУЖОМ сайте, то есть от кого угодно. Ячейка
    // `=cmd|'/c calc'!A1` без этой защиты выполняется у ВЛАДЕЛЬЦА сайта на его
    // машине, когда он открывает выгрузку.
    for (const raw of ['=1+1', '+1', '-1', '@SUM(A1)', '\t=cmd', '\r=cmd', '=HYPERLINK("http://evil")']) {
      const cell = csvCell(raw);
      const unquoted = cell.startsWith('"') ? cell.slice(1) : cell;
      expect(unquoted.startsWith("'"), `не обезврежено: ${JSON.stringify(raw)}`).toBe(true);
    }
    // Телефон `+7…` тоже получает апостроф — и это правильно: без него Excel
    // сам съедает плюс и ведущий ноль.
    expect(csvCell('+79990001122')).toBe("'+79990001122");
  });

  it('пустое значение — пустая ячейка, а не слово null', () => {
    expect(csvCell(null)).toBe('');
    expect(csvCell(undefined)).toBe('');
    expect(csvCell('')).toBe('');
  });

  it('дата сериализуется в ISO-8601, а не в локальную человеческую строку', () => {
    // Локальная строка (`toLocaleString`) зависит от таймзоны процесса: одна и
    // та же выгрузка на стенде и на проде дала бы разное время.
    expect(csvCell(new Date('2026-08-18T10:20:30.000Z'))).toBe('2026-08-18T10:20:30.000Z');
  });

  it('строка склеивается запятой и заканчивается CRLF', () => {
    expect(csvLine(['a', 'b,c', null])).toBe('a,"b,c",\r\n');
  });

  it('BOM — ровно U+FEFF: без него Excel читает кириллицу как мусор', () => {
    // Сравниваем с ЭКРАНИРОВАННЫМ литералом: невидимый символ в исходнике
    // невозможно отревьюить и легко потерять при копировании файла.
    expect(CSV_BOM).toBe('\uFEFF');
    expect(CSV_BOM).toHaveLength(1);
  });
});
