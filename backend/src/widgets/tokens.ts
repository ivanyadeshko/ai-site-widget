import { randomBytes } from 'node:crypto';

/**
 * Публичный токен виджета. НЕ секрет: он лежит в HTML чужого сайта открытым
 * текстом, и панель обязана это объяснять владельцу. Единственное требование —
 * неугадываемость: перебор чужих токенов не должен быть дешевле, чем перебор
 * 128 бит.
 *
 * Коллизия закрыта UNIQUE-индексом `widgets.publish_token` (init.cjs), а не
 * предварительным SELECT: между проверкой и вставкой токен успевает занять
 * параллельный запрос.
 */
export function generatePublishToken(): string {
  return `wgt_${randomBytes(16).toString('hex')}`;
}
