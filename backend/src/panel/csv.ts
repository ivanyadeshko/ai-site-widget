/**
 * CSV выгрузки кабинета.
 *
 * Файл открывают в Excel/Numbers/LibreOffice, а его содержимое пришло из формы
 * на ЧУЖОМ сайте — то есть от кого угодно. Отсюда две обязанности этого модуля:
 * не сломать структуру файла спецсимволами и не дать значению лида стать
 * исполняемой формулой у владельца на машине.
 */

/**
 * Метка порядка байт. Excel без неё читает UTF-8 как cp1251 и показывает
 * кириллицу мусором — а именно кириллица в выгрузке и есть основной контент.
 *
 * Записана ЭКРАНИРОВАННЫМ литералом намеренно: невидимый символ в исходнике
 * нельзя отревьюить и легко потерять при копировании файла.
 */
export const CSV_BOM = '\uFEFF';

/** Символы, при которых ячейку обязательно заворачивать в кавычки. */
const NEEDS_QUOTES_RE = /[",;\r\n]/;

/**
 * Начала, с которых табличный процессор считает ячейку ФОРМУЛОЙ.
 *
 * Классика атаки — `=cmd|'/c calc'!A1` в поле «комментарий»: Excel предложит
 * владельцу выполнить её при открытии выгрузки. Табуляция и CR здесь потому,
 * что Excel их отбрасывает и смотрит на следующий символ.
 */
const FORMULA_START_RE = /^[=+\-@\t\r]/;

/**
 * Значение → ячейка CSV.
 *
 * Порядок операций важен: сначала обезвреживаем формулу апострофом, и только
 * потом решаем про кавычки — иначе апостроф оказался бы ВНЕ кавычек и уехал бы
 * в соседнюю ячейку.
 */
export function csvCell(value: unknown): string {
  if (value === null || value === undefined) return '';
  // Дата — только ISO-8601: локальное представление зависит от таймзоны
  // процесса, и одна выгрузка на стенде и на проде разошлась бы по времени.
  const raw = value instanceof Date ? value.toISOString() : String(value);
  if (raw === '') return '';
  const guarded = FORMULA_START_RE.test(raw) ? `'${raw}` : raw;
  return NEEDS_QUOTES_RE.test(guarded) ? `"${guarded.replaceAll('"', '""')}"` : guarded;
}

/**
 * Строка CSV, завершённая CRLF (RFC 4180). Именно CRLF, а не `\n`: Excel на
 * Windows иначе склеивает строки в одну.
 */
export function csvLine(cells: unknown[]): string {
  return `${cells.map(csvCell).join(',')}\r\n`;
}
